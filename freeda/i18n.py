def translate(text: str, language: str) -> str:
    if language != "en":
        return text
    if text in EN:
        return EN[text]
    patterns = [
        (r"Batch exportieren \((\d+) Bilder\)", lambda m: "Export batch (" + m[1] + " images)"),
        (r"Verarbeitung (\d+/\d+): (.*)", lambda m: "Processing " + m[1] + ": " + m[2]),
        (r"Ausschnitt (\d+/\d+): (.*)", lambda m: "Crop " + m[1] + ": " + m[2]),
        (r"Foto (.*)", lambda m: "Photo " + m[1]),
        (r"Stereokarte (.*)", lambda m: "Stereo card " + m[1]),
        (r"Raumbildkarte (.*)", lambda m: "Raumbild card " + m[1]),
        (r"Breite: (.*) % je Halbbild", lambda m: "Width: " + m[1].replace(",", ".") + " % per view"),
        (r"Untertitelgröße: (.*) % je Halbbild", lambda m: "Caption size: " + m[1].replace(",", ".") + " % per view"),
        (r"(\d+) Bild(?:er)? gewählt", lambda m: m[1] + (" image selected" if m[1] == "1" else " images selected")),
        (r"Fertig – (\d+) Datei(?:en)?", lambda m: "Done – " + m[1] + (" file" if m[1] == "1" else " files")),
        (r"output/(web|print) bei der Eingabe", lambda m: "output/" + m[1] + " beside input"),
        (r"output/(web|print) im jeweiligen Eingabeordner", lambda m: "output/" + m[1] + " in each input folder"),
        (r"Freeda – Ausschnitt (.*)", lambda m: "Freeda – Crop " + m[1]),
        (r"Bild (\d+) von (\d+) — (.*)", lambda m: "Image " + m[1] + " of " + m[2] + " — " + m[3]),
        (r"Bild (\d+/\d+): (.*)", lambda m: "Image " + m[1] + ": " + m[2]),
        (r"Export abgebrochen – (\d+) Dateien exportiert", lambda m: "Export cancelled – " + m[1] + " files exported"),
        (r"Vorschaufehler:\n(.*)", lambda m: "Preview error:\n" + translate(m[1], "en")),
        (r"Vertikal: (.*)", lambda m: "Vertical: " + m[1]),
    ]
    for pattern, replacement in patterns:
        match = re.fullmatch(pattern, text, re.DOTALL)
        if match:
            return replacement(match)
    return text
